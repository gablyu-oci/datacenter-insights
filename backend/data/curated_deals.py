def get_curated_deals(company_filter: str | None = None) -> list[dict]:
    if company_filter and company_filter != "All":
        return [d for d in CURATED_DEALS
                if company_filter.lower() in d["buyer"].lower() or
                   company_filter.lower() in d.get("seller", "").lower()]
    return CURATED_DEALS


def get_company_gw_summary() -> dict:
    """Aggregate contracted GW by company from curated deals."""
    totals: dict[str, dict] = {}
    for deal in CURATED_DEALS:
        buyer = deal["buyer"].split(" / ")[0].split("/")[0].strip()
        # Simplify names
        for canon in ["Microsoft", "Amazon", "Google", "Meta", "Oracle"]:
            if canon.lower() in buyer.lower():
                buyer = canon
                break
        if buyer not in totals:
            totals[buyer] = {"gw_total": 0.0, "deals": 0, "nuclear_gw": 0.0, "renewable_gw": 0.0}
        mw = deal.get("capacity_mw") or 0
        gw = mw / 1000
        totals[buyer]["gw_total"] += gw
        totals[buyer]["deals"] += 1
        src = deal.get("energy_source", "").lower()
        if "nuclear" in src:
            totals[buyer]["nuclear_gw"] += gw
        elif any(r in src for r in ["solar", "wind", "renewable"]):
            totals[buyer]["renewable_gw"] += gw
    # Round
    for k in totals:
        for field in ["gw_total", "nuclear_gw", "renewable_gw"]:
            totals[k][field] = round(totals[k][field], 2)
    return totals
